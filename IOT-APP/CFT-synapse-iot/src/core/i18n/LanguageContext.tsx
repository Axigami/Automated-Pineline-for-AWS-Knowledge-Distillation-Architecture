export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLang] = useState<Language>(() => {
    const saved = localStorage.getItem('dashboard_lang');
    return (saved === 'en' || saved === 'vi') ? saved : 'en';
  });

  useEffect(() => {
    const handleLangChange = () => {
      const saved = localStorage.getItem('dashboard_lang');
      setLang((saved === 'en' || saved === 'vi') ? saved : 'en');
    };
    window.addEventListener('languageChange', handleLangChange);
    return () => window.removeEventListener('languageChange', handleLangChange);
  }, []);

  const setLanguage = (newLang: Language) => {
    localStorage.setItem('dashboard_lang', newLang);
    setLang(newLang);
    window.dispatchEvent(new Event('languageChange'));
  };

  const t = (module: string, key: string, ...args: any[]): string => {
    const template = GLOBAL_TRANSLATIONS[lang]?.[module]?.[key] || GLOBAL_TRANSLATIONS['en']?.[module]?.[key] || key;
    if (typeof template === 'function') {
      return template(...args);
    }
    return template;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
